export function createDictionary(): Trie {
  const trie = new Trie();

  // Add all 2-letter words
  for (const w of TWO_LETTER_WORDS) {
    trie.insert(w);
  }

  // Add all common words
  const words = COMMON_WORDS_RAW.split(/\s+/);
  for (const w of words) {
    if (w && w.length >= 2) {
      trie.insert(w);
    }
  }

  return trie;
}

// Singleton dictionary instance for quick access
let defaultDictionary: Trie | null = null;

export function getDefaultDictionary(): Trie {
  if (!defaultDictionary) {
    defaultDictionary = createDictionary();
  }
  return defaultDictionary;
}

export function isValidWord(word: string): boolean {
  return getDefaultDictionary().search(word);
}

